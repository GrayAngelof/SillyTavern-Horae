/**
* Фасад подсистемы состояния Horae.
*
* State является единственным источником истины для состояния чата.
* Отвечает за сбор, обработку и согласование данных из истории сообщений
* и метаданных, предоставляя потребителям единый снимок состояния.
*
* Состояние включает самостоятельные поля:
* * timestamp     — внутриигровые дата и время (time);
* * scene         — место и описание сцены (location, scene_desc, atmosphere);
* * characters    — персонажи, присутствующие в текущей сцене (characters);
* * costumes      — костюмы персонажей (costume);
* * items         — предметы, их владельцы и расположение (item);
* * events        — события истории (event из horaeevent);
* * affection     — значения привязанности персонажей (affection);
* * npcs          — данные и характеристики неигровых персонажей (npc);
* * agenda        — задачи и расписание (agenda);
* * mood          — эмоциональное состояние персонажей (mood);
* * relationships — отношения между персонажами.(rel)
*
* Правила архитектуры:
* * State отвечает за сбор и обработку всех перечисленных полей.
* * Каждое поле представляет самостоятельную сущность состояния;
* объединять разные сущности или подменять одну другой нельзя.
* * Присутствие персонажа в сцене и принадлежность к NPC учитываются
* независимо друг от друга.
* * Потребители используют готовый снимок State и не реконструируют
* состояние самостоятельно из истории сообщений и тегов.
* * Добавление, изменение и удаление данных учитываются при формировании
* итогового состояния.
* * Внутренняя реализация контроллера и специализированных подсистем
* скрыта за фасадом.
*/


import { StateController } from './state/_StateController.js';

export function createStateService(dependencies) {
    const controller = new StateController(dependencies);

    return {
        getLatestState(chat, skipLast = 0) {
            return controller.getLatestState(chat, skipLast);
        },
    };
}